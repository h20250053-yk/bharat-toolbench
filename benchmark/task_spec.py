"""Schema of a SEMANTIC task spec (benchmark/semantic_tasks.json).

A semantic task is language-independent: it never contains a language key or a query string.
Queries live in benchmark/languages/<lang>.jsonl; gold lives in benchmark/gold_labels.json and is
GENERATED by benchmark/build_gold.py from `solver` + the deterministic environment (never hand-edited).
"""
from __future__ import annotations

from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from .schemas import Category, ProhibitedAction


class SolverSpec(BaseModel):
    """Declarative, canonical description of what the task asks. `kind` selects a solver in build_gold.py."""

    model_config = ConfigDict(extra="forbid")
    kind: str
    params: dict[str, Any]


class InitialStateCheck(BaseModel):
    """A fact about the BASELINE environment that this task relies on; verified against a fresh env."""

    model_config = ConfigDict(extra="forbid")
    tool: str
    args: dict[str, Any]
    expect: dict[str, Any]  # subset of the tool's `data` that must match


class SemanticTaskSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    semantic_task_id: str
    category: Category
    playbook_note: str = ""
    task_goal: str
    constraints: list[dict[str, Any]]
    allowed_tools: list[str]
    solver: SolverSpec
    final_answer_requirements: dict[str, Any]
    initial_state_assumptions: list[str]
    # Only actions the user explicitly prohibits in the prompt; empty otherwise.
    prohibited_actions: list[ProhibitedAction] = Field(default_factory=list)
    initial_state_checks: list[InitialStateCheck] = Field(default_factory=list)
