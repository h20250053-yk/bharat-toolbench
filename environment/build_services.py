"""Deterministic generator for environment/data/services.json (benchmark 3.0, the 20-tool stage): Tatkal quota, berth split, platforms,
coach order, e-catering, TDR, complaint and boarding-change rules. Everything is SYNTHETIC (modelled loosely on Indian Railways
services; not the real tariff, not real platforms).

Usage:  python -m environment.build_services            # rewrites environment/data/services.json
        python -m environment.build_services --check    # exits 1 if the committed file differs from regeneration
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

DATA = Path(__file__).parent / "data"
OUT = DATA / "services.json"

# Tatkal: opens the day before the train leaves its origin, 10:00 for AC classes and 11:00 for SL (as on Indian Railways);
# the flat Tatkal charges and the per-train Tatkal seats are synthetic. Trains/classes not listed have no Tatkal seats.
TATKAL_SEATS = {"BTB101|2A": 4, "BTB101|3A": 6, "BTB102|2A": 4, "BTB103|2A": 5, "BTB103|3A": 0, "BTB103|SL": 8, "BTB104|2A": 4,
                "BTB104|3A": 6, "BTB104|SL": 10, "BTB106|CC": 4, "BTB107|SL": 6, "BTB108|SL": 5, "BTB109|2A": 5, "BTB109|3A": 6,
                "BTB110|2A": 3, "BTB110|3A": 5, "BTB111|3A": 5, "BTB111|SL": 8, "BTB112|3A": 4, "BTB112|SL": 10, "BTB114|CC": 3,
                "BTB118|CC": 4, "BTB119|3A": 4, "BTB119|SL": 5, "BTB120|SL": 6, "BTB121|2A": 2, "BTB121|3A": 4, "BTB124|SL": 8,
                "BTB126|CC": 5, "BTB127|SL": 6, "BTB128|SL": 6, "BTB130|CC": 0}
TATKAL_CHARGE = {"SL": 150, "3A": 350, "2A": 450, "CC": 100}
TATKAL_OPENS = {"2A": "10:00", "3A": "10:00", "CC": "10:00", "SL": "11:00"}

# Berth split of each class's baseline seats (largest remainder over these shares); overrides create the task situations.
BERTH_SHARES = {"SL": {"lower": 25, "middle": 20, "upper": 25, "side_lower": 15, "side_upper": 15},
                "3A": {"lower": 25, "middle": 20, "upper": 25, "side_lower": 15, "side_upper": 15},
                "2A": {"lower": 35, "upper": 35, "side_lower": 15, "side_upper": 15}}
BERTH_OVERRIDES = {"BTB122|2A": {"lower": 0, "upper": 14, "side_lower": 0, "side_upper": 10},
                   "BTB104|3A": {"lower": 0, "middle": 9, "upper": 10, "side_lower": 5, "side_upper": 5}}

COACHES = {"SL": ["S1", "S2", "S3", "S4"], "3A": ["B1", "B2", "B3"], "2A": ["A1", "A2"], "CC": ["C1", "C2", "C3", "C4"]}
CATERING = {"stations": ["ADI", "LKO", "MMCT", "NGP", "PUNE"],
            "menu_inr": {"veg_thali": 180, "nonveg_thali": 220, "jain_thali": 200, "breakfast": 120},
            "serving_hours": {"breakfast": ["06:00", "10:59"], "veg_thali": ["11:00", "23:00"], "nonveg_thali": ["11:00", "23:00"],
                              "jain_thali": ["11:00", "23:00"]},
            "min_lead_minutes": 120, "max_quantity": 6}
TDR = {"min_delay_minutes": 180, "rule": "train late by at least 180 minutes AND filed before it actually leaves the boarding station; refund = full fare"}
COMPLAINTS = {"categories": ["cleanliness", "ac_not_working", "water_shortage", "catering", "security", "punctuality", "other"],
              "ac_classes_only": ["ac_not_working"]}
BOARDING_CHANGE = {"min_hours_before_departure": 24}


def _split(n: int, shares: dict[str, int]) -> dict[str, int]:
    raw = {k: n * v / 100 for k, v in shares.items()}
    out = {k: int(x) for k, x in raw.items()}
    for k in sorted(raw, key=lambda k: (-(raw[k] - out[k]), list(shares).index(k)))[: n - sum(out.values())]:
        out[k] += 1
    return out


def build() -> dict:
    trains = json.loads((DATA / "trains.json").read_text(encoding="utf-8"))["trains"]
    berths, platforms, coach_order = {}, {}, {}
    for t in trains:
        tid = t["train_id"]
        for cls, info in sorted(t["classes"].items()):
            if cls in BERTH_SHARES:
                key = f"{tid}|{cls}"
                b = BERTH_OVERRIDES.get(key) or _split(info["seats"], BERTH_SHARES[cls])
                assert sum(b.values()) == info["seats"], key
                berths[key] = b
        for s in t["stops"]:  # synthetic platform numbers 1-8, fixed per (train, station)
            platforms[f"{tid}|{s['station']}"] = 1 + sum(map(ord, tid + s["station"])) % 8
        order = ["ENGINE", "GEN"]
        for cls in ("SL", "3A", "2A", "CC"):
            if cls in t["classes"]:
                order += COACHES[cls]
        coach_order[tid] = order + (["PANTRY"] if t["train_type"] in ("premium", "sf") else []) + ["GEN", "GUARD"]
    return {"_comment": "SYNTHETIC services for BharatToolBench 3.0 (20-tool stage). Generated by environment/build_services.py; do not hand-edit. "
                        "Tatkal opening times follow Indian Railways (AC 10:00, SL 11:00, the day before departure from the origin); every "
                        "other number here is invented.",
            "tatkal": {"opens_at": TATKAL_OPENS, "charge_inr": TATKAL_CHARGE, "seats": dict(sorted(TATKAL_SEATS.items())),
                       "concessions_allowed": False},
            "berths": berths, "platforms": platforms, "coach_order": coach_order, "catering": CATERING, "tdr": TDR,
            "complaints": COMPLAINTS, "boarding_change": BOARDING_CHANGE}


def render() -> str:
    return json.dumps(build(), ensure_ascii=False, indent=1) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        return 0 if OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
